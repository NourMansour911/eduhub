from datetime import datetime, timezone
from typing import Any, Dict, Optional
from pydantic import Field, BaseModel, model_validator
from models.mongo_document_model import MongoDocumentModel

class RequestLayer(BaseModel):
    user_query: str = Field(..., description="The user's input/query")
    session_id: Optional[str] = None
    student_id: Optional[str] = None
    context_data: Dict[str, Any] = Field(
        default_factory=dict, 
        description="Any conversational history, user persona, or session state snapshots"
    )

    model_config = {"extra": "allow"}

class RetrievalLayer(BaseModel):
    raw_documents: Optional[list[Dict[str, Any]]] = Field(
        default=None, 
        description="List of raw docs/chunks returned by search services (with score, metadata, text)"
    )
    final_context: Optional[str] = Field(
        default=None, 
        description="The aggregated/processed string injected into the final LLM prompt"
    )
    config: Dict[str, Any] = Field(
        default_factory=dict, 
        description="Retrieval config, e.g., rewrite_mode, search_strategy, top_k, reranking_enabled"
    )

    model_config = {"extra": "allow"}

class GenerationLayer(BaseModel):
    final_answer: str = Field(..., description="The final reply generated by the chatbot")

    model_config = {"extra": "allow"}

class PerformanceLayer(BaseModel):
    latency_ms: Optional[float] = Field(None, description="Total execution time of the chatbot request in milliseconds")
    token_usage: Dict[str, Any] = Field(
        default_factory=dict, 
        description="Unified hierarchical tree keyed by node name. Each node contains both usage and metadata payloads."
    )
    cost: Optional[float] = Field(None, description="Calculated query cost in USD")

    model_config = {"extra": "allow"}

    @staticmethod
    def _merge_unified_tree(usage_tree: Any, metadata_tree: Any) -> Any:
        if not isinstance(usage_tree, dict):
            return usage_tree

        unified_tree: Dict[str, Any] = {}
        for key, value in usage_tree.items():
            if key == "total":
                if isinstance(value, dict) and ("usage" in value or "metadata" in value):
                    unified_tree[key] = {
                        "usage": value.get("usage", {}) if isinstance(value.get("usage"), dict) else {},
                        "metadata": value.get("metadata", {}) if isinstance(value.get("metadata"), dict) else {},
                    }
                else:
                    unified_tree[key] = {
                        "usage": value if isinstance(value, dict) else {},
                        "metadata": {},
                    }
                continue

            metadata_value = metadata_tree.get(key, {}) if isinstance(metadata_tree, dict) else {}
            if isinstance(value, dict) and ("usage" in value or "metadata" in value):
                unified_tree[key] = {
                    "usage": value.get("usage", {}) if isinstance(value.get("usage"), dict) else {},
                    "metadata": value.get("metadata", {}) if isinstance(value.get("metadata"), dict) else metadata_value if isinstance(metadata_value, dict) else {},
                }
            elif isinstance(value, dict):
                unified_tree[key] = PerformanceLayer._merge_unified_tree(value, metadata_value)
            else:
                unified_tree[key] = {
                    "usage": {},
                    "metadata": metadata_value if isinstance(metadata_value, dict) else {},
                }

        return unified_tree

    @model_validator(mode="before")
    @classmethod
    def migrate_legacy_usage_fields(cls, value: Any) -> Any:
        if not isinstance(value, dict):
            return value

        migrated_value = dict(value)
        legacy_metadata_tree = migrated_value.pop("llm_metadata", None)
        legacy_usage_tree = migrated_value.get("token_usage")

        metrics = migrated_value.pop("metrics", None)
        if isinstance(metrics, dict):
            legacy_usage = metrics.pop("llm_usage_breakdown", None)
            legacy_metadata = metrics.pop("llm_metadata_breakdown", None)
            if legacy_usage_tree is None and legacy_usage is not None:
                legacy_usage_tree = legacy_usage
            if legacy_metadata_tree is None and legacy_metadata is not None:
                legacy_metadata_tree = legacy_metadata

        if isinstance(legacy_usage_tree, dict) and legacy_usage_tree:
            migrated_value["token_usage"] = cls._merge_unified_tree(legacy_usage_tree, legacy_metadata_tree)

        return migrated_value

class EvaluationMetricsLayer(BaseModel):
    is_evaluated: bool = Field(default=False, description="Flag indicating whether an evaluation run has executed")
    evaluated_at: Optional[datetime] = Field(None, description="Timestamp of when the evaluation occurred")
    judge_info: Dict[str, Any] = Field(
        default_factory=dict, 
        description="Metadata on the judge model or framework used (e.g. gpt-4o, ragas 0.2.0)"
    )
    metrics: Dict[str, Any] = Field(
        default_factory=dict, 
        description="Key-value pairs of metrics (e.g., faithfulness: 0.9, answer_relevancy: 0.85)"
    )

    model_config = {"extra": "allow"}

class EvaluationModel(MongoDocumentModel):
    created_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))
    request: RequestLayer
    retrieval: RetrievalLayer
    generation: GenerationLayer
    performance: PerformanceLayer
    evaluation: EvaluationMetricsLayer = Field(default_factory=EvaluationMetricsLayer)

    model_config = {
        "extra": "allow",
        "populate_by_name": True,
    }
