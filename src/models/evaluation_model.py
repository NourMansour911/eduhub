from datetime import datetime, timezone
from typing import Any, Dict, Optional
from pydantic import Field, BaseModel
from models.mongo_document_model import MongoDocumentModel

class RequestLayer(BaseModel):
    user_query: str = Field(..., description="The user's input/query")
    session_id: Optional[str] = None
    student_id: Optional[str] = None
    context_data: Dict[str, Any] = Field(
        default_factory=dict, 
        description="Any conversational history, user persona, or session state snapshots"
    )

    model_config = {"extra": "allow"}

class RetrievalLayer(BaseModel):
    raw_documents: Optional[list[Dict[str, Any]]] = Field(
        default=None, 
        description="List of raw docs/chunks returned by search services (with score, metadata, text)"
    )
    final_context: Optional[str] = Field(
        default=None, 
        description="The aggregated/processed string injected into the final LLM prompt"
    )
    config: Dict[str, Any] = Field(
        default_factory=dict, 
        description="Retrieval config, e.g., rewrite_mode, search_strategy, top_k, reranking_enabled"
    )

    model_config = {"extra": "allow"}

class GenerationLayer(BaseModel):
    final_answer: str = Field(..., description="The final reply generated by the chatbot")
    prompt_context: Optional[str] = Field(
        default=None, 
        description="System instructions, template structures, or full prompt template utilized"
    )
    parameters: Dict[str, Any] = Field(
        default_factory=dict, 
        description="LLM invocation parameters (temperature, model, max_tokens, etc.)"
    )
    metadata: Dict[str, Any] = Field(
        default_factory=dict, 
        description="LLM provider metadata (finish_reason, system_fingerprint, API version)"
    )

    model_config = {"extra": "allow"}

class PerformanceLayer(BaseModel):
    latency_ms: Optional[float] = Field(None, description="Total execution time of the chatbot request in milliseconds")
    token_usage: Dict[str, Any] = Field(
        default_factory=dict, 
        description="Token details (prompt_tokens, completion_tokens, total_tokens)"
    )
    cost: Optional[float] = Field(None, description="Calculated query cost in USD")
    metrics: Dict[str, Any] = Field(
        default_factory=dict, 
        description="Custom latency steps or performance markers from internal services"
    )

    model_config = {"extra": "allow"}

class EvaluationMetricsLayer(BaseModel):
    is_evaluated: bool = Field(default=False, description="Flag indicating whether an evaluation run has executed")
    evaluated_at: Optional[datetime] = Field(None, description="Timestamp of when the evaluation occurred")
    judge_info: Dict[str, Any] = Field(
        default_factory=dict, 
        description="Metadata on the judge model or framework used (e.g. gpt-4o, ragas 0.2.0)"
    )
    metrics: Dict[str, Any] = Field(
        default_factory=dict, 
        description="Key-value pairs of metrics (e.g., faithfulness: 0.9, answer_relevancy: 0.85)"
    )

    model_config = {"extra": "allow"}

class EvaluationModel(MongoDocumentModel):
    created_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))
    request: RequestLayer
    retrieval: RetrievalLayer
    generation: GenerationLayer
    performance: PerformanceLayer
    evaluation: EvaluationMetricsLayer = Field(default_factory=EvaluationMetricsLayer)

    model_config = {
        "extra": "allow",
        "populate_by_name": True,
    }
